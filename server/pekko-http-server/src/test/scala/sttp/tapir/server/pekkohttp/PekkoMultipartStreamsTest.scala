package sttp.tapir.server.pekkohttp

import org.apache.pekko.NotUsed
import org.apache.pekko.actor.ActorSystem
import org.apache.pekko.http.scaladsl.model.EntityStreamSizeException
import org.apache.pekko.stream.Materializer
import org.apache.pekko.stream.scaladsl.{Sink, Source}
import org.apache.pekko.util.ByteString
import org.scalatest.BeforeAndAfterAll
import org.scalatest.funsuite.AsyncFunSuite
import org.scalatest.matchers.should.Matchers
import sttp.model.Part
import sttp.tapir.server.model.InvalidMultipartBodyException

import java.util.concurrent.atomic.AtomicLong
import scala.concurrent.Future

class PekkoMultipartStreamsTest extends AsyncFunSuite with Matchers with BeforeAndAfterAll {
  private implicit val system: ActorSystem = ActorSystem("PekkoMultipartStreamsTest")
  private implicit val mat: Materializer = Materializer(system)

  override protected def afterAll(): Unit = {
    val _ = system.terminate()
    super.afterAll()
  }

  private val boundary = "XyZb0undary"
  private val crlf = ByteString("\r\n")
  private val q = "\""
  private val closing = ByteString(s"\r\n--$boundary--\r\n")

  private def partHeader(name: String, fileName: Option[String] = None, extraHeaders: List[String] = Nil): ByteString =
    ByteString(
      s"--$boundary\r\nContent-Disposition: form-data; name=$q$name$q${fileName.fold("")(f => s"; filename=$q$f$q")}\r\n" +
        "Content-Type: application/octet-stream\r\n" +
        extraHeaders.map(_ + "\r\n").mkString +
        "\r\n"
    )

  private val chunkSize = 64 * 1024
  private val fileChunk = ByteString(Array.fill[Byte](chunkSize)('x'.toByte))
  private val bigBodyPrefix = partHeader("a") ++ ByteString("hello") ++ crlf ++ partHeader("f", Some("big.bin"))
  private val bigBodySuffix = crlf ++ partHeader("b") ++ ByteString("world") ++ closing

  /** Field "a"=hello, file "f" of `fileSize` lazily generated bytes, field "b"=world. Counts the bytes read from the source. */
  private def bigBody(fileSize: Long, pulled: AtomicLong = new AtomicLong()): Source[ByteString, NotUsed] =
    (Source.single(bigBodyPrefix) ++ Source(1 to (fileSize / chunkSize).toInt).map(_ => fileChunk) ++ Source.single(bigBodySuffix))
      .map { b => pulled.addAndGet(b.size.toLong); b }

  private def bigBodySize(fileSize: Long): Long = bigBodyPrefix.size + fileSize + bigBodySuffix.size

  /** Collects each part with its full body (as a string). */
  private def collect(events: Source[Either[Part[Unit], ByteString], Any]): Future[List[(Part[Unit], String)]] =
    events
      .runFold(Vector.empty[(Part[Unit], ByteString)]) {
        case (acc, Left(part))   => acc :+ (part -> ByteString.empty)
        case (acc, Right(bytes)) => acc.init :+ (acc.last._1 -> (acc.last._2 ++ bytes))
      }
      .map(_.toList.map { case (p, b) => p -> b.utf8String })

  private def failureOf(events: Source[Either[Part[Unit], ByteString], Any]): Future[Throwable] =
    events.runWith(Sink.ignore).failed

  test("parse parts with their metadata") {
    val body = partHeader("a") ++ ByteString("hello") ++ crlf ++
      partHeader("f", Some("data.txt"), List("X-Custom: v1")) ++ ByteString("file content") ++ closing

    collect(PekkoMultipartStreams.parse(boundary, Source.single(body))).map { parts =>
      parts.map { case (p, b) => (p.name, p.fileName, p.contentType, b) } shouldBe List(
        ("a", None, Some("application/octet-stream"), "hello"),
        ("f", Some("data.txt"), Some("application/octet-stream"), "file content")
      )
      parts(1)._1.header("X-Custom") shouldBe Some("v1")
    }
  }

  test("handle delimiters split across chunks, a preamble, an epilogue and an empty part") {
    val body = ByteString("this is a preamble\r\n") ++
      partHeader("a") ++ ByteString("hel\r\nlo-") ++ crlf ++
      partHeader("f", Some("x.txt")) ++ ByteString(s"almost --$boundary but not") ++ crlf ++
      partHeader("empty") ++ closing ++ ByteString("epilogue")

    Future
      .sequence(List(1, 3, 7, 64, body.size).map { size =>
        collect(PekkoMultipartStreams.parse(boundary, Source(body.grouped(size).toList))).map(_.map { case (p, b) => p.name -> b })
      })
      .map { results =>
        results.distinct shouldBe List(List("a" -> "hel\r\nlo-", "f" -> s"almost --$boundary but not", "empty" -> ""))
      }
  }

  test("stream a large part without buffering it") {
    val fileSize = 512L * 1024 * 1024
    val pulled = new AtomicLong()

    PekkoMultipartStreams
      .parse(boundary, bigBody(fileSize, pulled))
      .dropWhile(!_.left.exists(_.name == "f"))
      .take(2) // the "f" part's header and its first chunk
      .runWith(Sink.seq)
      .map { events =>
        events.head.left.map(_.fileName) shouldBe Left(Some("big.bin"))
        events(1).isRight shouldBe true
        pulled.get() should be < (1024L * 1024)
      }
  }

  test("emit all the bytes of a large part, in small chunks") {
    val fileSize = 64L * 1024 * 1024

    PekkoMultipartStreams
      .parse(boundary, bigBody(fileSize))
      .runFold((Vector.empty[String], Map.empty[String, Long], 0)) {
        case ((names, sizes, maxChunk), Left(part))   => (names :+ part.name, sizes, maxChunk)
        case ((names, sizes, maxChunk), Right(bytes)) =>
          (names, sizes.updated(names.last, sizes.getOrElse(names.last, 0L) + bytes.size), math.max(maxChunk, bytes.size))
      }
      .map { case (names, sizes, maxChunk) =>
        names shouldBe Vector("a", "f", "b")
        sizes shouldBe Map("a" -> 5L, "f" -> fileSize, "b" -> 5L)
        maxChunk should be <= (1024 * 1024)
      }
  }

  test("skip parts when their bytes are ignored") {
    PekkoMultipartStreams
      .parse(boundary, bigBody(8L * 1024 * 1024))
      .collect { case Left(part) => part.name }
      .runWith(Sink.seq)
      .map(_ shouldBe Seq("a", "f", "b"))
  }

  test("don't read the body until the stream is materialized") {
    val pulled = new AtomicLong()
    val _ = PekkoMultipartStreams.parse(boundary, bigBody(1024L * 1024, pulled))
    Future(Thread.sleep(100)).map(_ => pulled.get() shouldBe 0L)
  }

  test("fail with InvalidMultipartBodyException given a malformed part header") {
    val body = ByteString(s"--$boundary\r\nno-colon-header\r\n\r\nbody$closing")
    failureOf(PekkoMultipartStreams.parse(boundary, Source.single(body))).map(_ shouldBe an[InvalidMultipartBodyException])
  }

  test("fail with InvalidMultipartBodyException given a truncated body") {
    val body = partHeader("a") ++ ByteString("hello, cut off here")
    failureOf(PekkoMultipartStreams.parse(boundary, Source(body.grouped(4).toList))).map(_ shouldBe an[InvalidMultipartBodyException])
  }

  test("fail with InvalidMultipartBodyException given a boundary which doesn't match the body") {
    val body = partHeader("a") ++ ByteString("hello") ++ closing
    failureOf(PekkoMultipartStreams.parse("other", Source.single(body))).map(_ shouldBe an[InvalidMultipartBodyException])
  }

  test("propagate errors from the body stream unchanged") {
    val fileSize = 16L * 1024 * 1024
    val limited = org.apache.pekko.http.scaladsl.model.HttpEntity
      .Default(org.apache.pekko.http.scaladsl.model.ContentTypes.`application/octet-stream`, bigBodySize(fileSize), bigBody(fileSize))
      .withSizeLimit(1024L * 1024)
      .dataBytes
    failureOf(PekkoMultipartStreams.parse(boundary, limited)).map(_ shouldBe an[EntityStreamSizeException])
  }

  // helpers

  test("singlePart: extract the body of a part") {
    val fileSize = 8L * 1024 * 1024
    PekkoMultipartStreams
      .parse(boundary, bigBody(fileSize))
      .via(PekkoMultipartStreams.singlePart("f"))
      .runFold(0L)(_ + _.size)
      .map(_ shouldBe fileSize)
  }

  test("singlePart: extract the last part") {
    PekkoMultipartStreams
      .parse(boundary, bigBody(1024L * 1024))
      .via(PekkoMultipartStreams.singlePart("b"))
      .runFold(ByteString.empty)(_ ++ _)
      .map(_.utf8String shouldBe "world")
  }

  test("singlePart: stop reading the body once the part ends") {
    val fileSize = 64L * 1024 * 1024
    val pulled = new AtomicLong()
    PekkoMultipartStreams
      .parse(boundary, bigBody(fileSize, pulled))
      .via(PekkoMultipartStreams.singlePart("a"))
      .runFold(ByteString.empty)(_ ++ _)
      .map { bytes =>
        bytes.utf8String shouldBe "hello"
        pulled.get() should be < (1024L * 1024)
      }
  }

  test("singlePart: fail with InvalidMultipartBodyException if the part is missing") {
    failureOf(PekkoMultipartStreams.parse(boundary, bigBody(1024L * 1024)).via(PekkoMultipartStreams.singlePart("missing")).map(Right(_)))
      .map { e =>
        e shouldBe an[InvalidMultipartBodyException]
        e.getMessage should include("missing")
      }
  }

  test("groupParts: emit each part with its byte stream") {
    val fileSize = 8L * 1024 * 1024
    PekkoMultipartStreams
      .parse(boundary, bigBody(fileSize))
      .via(PekkoMultipartStreams.groupParts)
      .mapAsync(1) { case (part, bytes) => bytes.runFold(0L)(_ + _.size).map(part.name -> _) }
      .runWith(Sink.seq)
      .map(_ shouldBe Seq("a" -> 5L, "f" -> fileSize, "b" -> 5L))
  }

  test("foreachPart: run each part with a different sink") {
    val fileSize = 8L * 1024 * 1024
    PekkoMultipartStreams
      .parse(boundary, bigBody(fileSize))
      .via(PekkoMultipartStreams.foreachPart[String] {
        case p if p.fileName.isDefined => Sink.fold[Long, ByteString](0L)(_ + _.size).mapMaterializedValue(_.map(n => s"$n bytes"))
        case _ => Sink.fold[ByteString, ByteString](ByteString.empty)(_ ++ _).mapMaterializedValue(_.map(_.utf8String))
      })
      .map { case (part, result) => part.name -> result }
      .runWith(Sink.seq)
      .map(_ shouldBe Seq("a" -> "hello", "f" -> s"$fileSize bytes", "b" -> "world"))
  }

  test("foreachPart: continue with the next part when a sink stops early") {
    PekkoMultipartStreams
      .parse(boundary, bigBody(8L * 1024 * 1024))
      .via(PekkoMultipartStreams.foreachPart(_ => Sink.headOption[ByteString].mapMaterializedValue(_.map(_.map(_.take(3).utf8String)))))
      .map { case (part, result) => part.name -> result }
      .runWith(Sink.seq)
      .map(_ shouldBe Seq("a" -> Some("hel"), "f" -> Some("xxx"), "b" -> Some("wor")))
  }

  test("foreachPart: propagate failures of a sink") {
    PekkoMultipartStreams
      .parse(boundary, bigBody(1024L * 1024))
      .via(PekkoMultipartStreams.foreachPart(_ => Sink.foreach[ByteString](_ => throw new RuntimeException("boom"))))
      .runWith(Sink.ignore)
      .failed
      .map(_.getMessage shouldBe "boom")
  }
}
